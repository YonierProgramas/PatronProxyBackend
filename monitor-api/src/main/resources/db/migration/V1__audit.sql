CREATE TABLE audit_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 service_id VARCHAR(20) NOT NULL,
 operation VARCHAR(100) NOT NULL,
 duration_ms DOUBLE PRECISION NOT NULL,
 status VARCHAR(10) NOT NULL CHECK (status IN ('SUCCESS','ERROR')),
 request_id VARCHAR(36) NOT NULL UNIQUE,
 timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
 input_params TEXT NOT NULL,
 response TEXT,
 error_code VARCHAR(60),
 error_message VARCHAR(500),
 stack_trace_summary VARCHAR(1500)
);
CREATE INDEX audit_time_idx ON audit_log(timestamp DESC,id DESC);
CREATE INDEX audit_service_time_idx ON audit_log(service_id,timestamp DESC,id DESC);
